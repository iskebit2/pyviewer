def interpolate_cpe(cpe_type, angle, parameter, wdir, data):
    """
    data[wdir][cpe_type][angle][parameter] yapısından
    lineer interpolasyon ile değer döndürür.
    """

    # Wind direction
    if wdir not in data:
        raise KeyError(f"wdir={wdir} data içinde bulunamadı.")

    # CPE type
    if cpe_type not in data[wdir]:
        raise KeyError(
            f"cpe_type={cpe_type}, wdir={wdir} içinde bulunamadı."
        )

    table = data[wdir][cpe_type]

    # Mevcut açı değerleri
    angles = sorted(table.keys())

    # İstenen region gerçekten mevcut mu?
    if parameter not in {
        region
        for angle_data in table.values()
        for region in angle_data
    }:
        raise KeyError(
            f"region={parameter}, wdir={wdir}, cpe_type={cpe_type} "
            f"içinde bulunamadı."
        )

    # --------------------------------------------------
    # Sınırların dışında -> en yakın sınır değerini kullan
    # --------------------------------------------------

    if angle <= angles[0]:
        if parameter not in table[angles[0]]:
            raise KeyError(
                f"{parameter} region'i angle={angles[0]} değerinde yok."
            )

        return table[angles[0]][parameter].copy()

    if angle >= angles[-1]:
        if parameter not in table[angles[-1]]:
            raise KeyError(
                f"{parameter} region'i angle={angles[-1]} değerinde yok."
            )

        return table[angles[-1]][parameter].copy()

    # --------------------------------------------------
    # İki açı arasındaki interpolasyon
    # --------------------------------------------------

    for a1, a2 in zip(angles[:-1], angles[1:]):

        if a1 <= angle <= a2:

            # Region iki noktada da mevcut değilse
            # interpolasyon yapılamaz.
            if parameter not in table[a1]:
                raise KeyError(
                    f"{parameter} region'i angle={a1} değerinde yok."
                )

            if parameter not in table[a2]:
                raise KeyError(
                    f"{parameter} region'i angle={a2} değerinde yok."
                )

            v1 = table[a1][parameter]
            v2 = table[a2][parameter]

            # Aynı açı ise direkt değeri döndür
            if a1 == a2:
                return v1.copy()

            # Interpolation coefficient
            t = (angle - a1) / (a2 - a1)

            return [
    round(v1[i] + t * (v2[i] - v1[i]), 6)
    for i in range(len(v1))
]


    raise ValueError(
        f"angle={angle} için interpolasyon yapılamadı."
    )


def get_all_zones(data):
    zones = set()

    def traverse(obj):
        if not isinstance(obj, dict):
            return

        # {'F': [-1.7, 0], 'G': [-1.2, 0], ...}
        if obj and all(
            isinstance(v, (list, tuple))
            and len(v) == 2
            and all(isinstance(x, (int, float)) for x in v)
            for v in obj.values()
        ):
            zones.update(obj.keys())
            return

        for value in obj.values():
            traverse(value)

    traverse(data)

    return sorted(zones)

